-- Type enum pour les catégories de prix
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'prize_category_enum') THEN
        CREATE TYPE prize_category_enum AS ENUM (
            'discount',        -- Réductions (% ou montant fixe)
            'free_ticket',     -- Billet gratuit
            'upgrade',         -- Upgrade de catégorie
            'extra_play'       -- Tirage supplémentaire
        );
    END IF;
END
$$;

-- Table des prix disponibles
CREATE TABLE IF NOT EXISTS aiolia.ticket_chance_prizes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    
    -- Identification
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    
    -- Catégorie et valeur
    category prize_category_enum NOT NULL,
    value_type VARCHAR(20) NOT NULL DEFAULT 'fixed', -- 'fixed', 'percent', 'quantity'
    value NUMERIC(12,2) NOT NULL,
    
    -- Affichage sur la roue
    display_label VARCHAR(50) NOT NULL,
    color VARCHAR(7) NOT NULL DEFAULT '#4A90E2', -- Couleur hex
    icon VARCHAR(50) DEFAULT 'fa-gift',
    
    -- Probabilité et limites
    probability NUMERIC(5,4) NOT NULL DEFAULT 0.1000, -- 10% par défaut
    max_wins_per_day INTEGER,           -- Limite par jour (NULL = illimité)
    max_wins_per_user INTEGER,          -- Limite par utilisateur (NULL = illimité)
    
    -- Validité du prix gagné
    validity_days INTEGER DEFAULT 30,   -- Durée de validité après gain
    
    -- Conditions d'application
    min_order_amount NUMERIC(12,2),     -- Montant minimum pour utiliser
    applicable_categories TEXT[],        -- Catégories d'événements applicables
    applicable_event_ids BIGINT[],       -- Événements spécifiques applicables
    
    -- État
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    display_order INTEGER NOT NULL DEFAULT 0,
    
    -- Métadonnées
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Index pour les recherches
CREATE INDEX IF NOT EXISTS idx_ticket_chance_prizes_active 
    ON aiolia.ticket_chance_prizes(is_active, display_order);

