-- ============================================================
-- MODIFIER LA TABLE ticket_chance_entries POUR RÉFÉRENCER LES PRIX
-- ============================================================

-- Ajouter la colonne prize_id si elle n'existe pas
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns 
        WHERE table_schema = 'aiolia' 
        AND table_name = 'ticket_chance_entries' 
        AND column_name = 'prize_id'
    ) THEN
        ALTER TABLE aiolia.ticket_chance_entries 
        ADD COLUMN prize_id BIGINT REFERENCES aiolia.ticket_chance_prizes(id);
        
        -- Index pour les jointures
        CREATE INDEX IF NOT EXISTS idx_ticket_chance_entries_prize 
            ON aiolia.ticket_chance_entries(prize_id);
    END IF;
END
$$;

-- ============================================================
-- VUE POUR RÉCUPÉRER LES PRIX ACTIFS AVEC LEURS PROBABILITÉS
-- ============================================================

CREATE OR REPLACE VIEW aiolia.v_active_prizes AS
SELECT 
    id,
    code,
    name,
    description,
    category,
    value_type,
    value,
    display_label,
    color,
    icon,
    probability,
    validity_days,
    min_order_amount,
    applicable_categories,
    applicable_event_ids
FROM aiolia.ticket_chance_prizes
WHERE is_active = TRUE
ORDER BY display_order;

-- Vérifier que les probabilités totalisent 100%
SELECT 
    SUM(probability) as total_probability,
    CASE 
        WHEN SUM(probability) = 1.0 THEN '✓ Probabilités correctes (100%)'
        ELSE '⚠ Attention: probabilités = ' || (SUM(probability) * 100)::TEXT || '%'
    END as status
FROM aiolia.ticket_chance_prizes
WHERE is_active = TRUE;

